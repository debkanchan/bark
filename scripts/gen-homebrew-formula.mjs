#!/usr/bin/env node
// Generate the Homebrew formula for bark.
//
//   node scripts/gen-homebrew-formula.mjs <version> <artifacts-dir> <out-file>
//
// - <version>       e.g. "0.1.2" (no leading "v")
// - <artifacts-dir> directory of downloaded release artifacts, layout:
//                     <artifacts-dir>/bark-<os>-<arch>/bark-<os>-<arch>.tar.gz.sha256
// - <out-file>      where to write the formula, e.g. Formula/bark.rb
//
// Homebrew is unix-only here (Windows ships via npm), so the formula covers the
// four macOS/Linux × amd64/arm64 archives.

import { promises as fs } from "node:fs";
import path from "node:path";

const REPO = "debkanchan/bark";

// Homebrew block -> release artifact (os/arch use the release naming).
const TARGETS = [
  { macos: true, arm: true, os: "darwin", arch: "arm64" },
  { macos: true, arm: false, os: "darwin", arch: "amd64" },
  { macos: false, arm: true, os: "linux", arch: "arm64" },
  { macos: false, arm: false, os: "linux", arch: "amd64" },
];

async function sha256For(artifactsDir, os, arch) {
  const file = path.join(
    artifactsDir,
    `bark-${os}-${arch}`,
    `bark-${os}-${arch}.tar.gz.sha256`
  );
  const contents = await fs.readFile(file, "utf8");
  const sha = contents.trim().split(/\s+/)[0];
  if (!/^[0-9a-f]{64}$/.test(sha)) {
    throw new Error(`unexpected sha256 in ${file}: "${sha}"`);
  }
  return sha;
}

function archiveUrl(version, os, arch) {
  return `https://github.com/${REPO}/releases/download/v${version}/bark-${os}-${arch}.tar.gz`;
}

function block(version, t, sha) {
  // Only url + sha256 per platform. Installation is a single top-level
  // `install` method — Homebrew's RuboCop forbids defining methods inside the
  // on_macos/on_linux blocks.
  const url = archiveUrl(version, t.os, t.arch);
  return [`      url "${url}"`, `      sha256 "${sha}"`].join("\n");
}

async function main() {
  const [, , version, artifactsDir, outFile] = process.argv;
  if (!version || !artifactsDir || !outFile) {
    console.error(
      "usage: node scripts/gen-homebrew-formula.mjs <version> <artifacts-dir> <out-file>"
    );
    process.exit(1);
  }

  const sha = {};
  for (const t of TARGETS) {
    sha[`${t.os}-${t.arch}`] = await sha256For(artifactsDir, t.os, t.arch);
  }

  const darwinArm = TARGETS.find((t) => t.macos && t.arm);
  const darwinIntel = TARGETS.find((t) => t.macos && !t.arm);
  const linuxArm = TARGETS.find((t) => !t.macos && t.arm);
  const linuxIntel = TARGETS.find((t) => !t.macos && !t.arm);

  const formula = `# typed: false
# frozen_string_literal: true

# This file is generated by scripts/gen-homebrew-formula.mjs on release.
# Do not edit by hand.
class Bark < Formula
  desc "Embarrassment linter that detects BARK comments in your code"
  homepage "https://github.com/${REPO}"
  version "${version}"
  license "AGPL-3.0-or-later"

  on_macos do
    on_arm do
${block(version, darwinArm, sha["darwin-arm64"])}
    end
    on_intel do
${block(version, darwinIntel, sha["darwin-amd64"])}
    end
  end

  on_linux do
    on_arm do
${block(version, linuxArm, sha["linux-arm64"])}
    end
    on_intel do
${block(version, linuxIntel, sha["linux-amd64"])}
    end
  end

  def install
    # Each archive contains a single platform-suffixed binary; install it as "bark".
    bin.install Dir["bark-*"].first => "bark"
  end

  test do
    # bark prints its usage to stderr, so redirect it into the captured output.
    assert_match "Bark", shell_output("#{bin}/bark --help 2>&1")
  end
end
`;

  await fs.mkdir(path.dirname(outFile), { recursive: true });
  await fs.writeFile(outFile, formula);
  console.log(`wrote ${outFile} (bark ${version})`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
